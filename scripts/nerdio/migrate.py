"""Upgrade v1 setup.auto.tfvars.json and Terraform state to the v2 multi-region regions map.

Standard library only. Writes upgraded setup.auto.tfvars.json files and generates
migrations.auto.tf with Terraform `moved` blocks in 01-platform and 02-nerdio-config
for zero-downtime state migration.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

import engine


def upgrade_platform_tfvars(v1: dict) -> dict:
    """Upgrade a v1 01-platform tfvars dictionary to the v2 regions map structure."""
    if "regions" in v1 and "control_plane_location" in v1:
        return dict(v1)
    out = dict(v1)
    location = out.pop("location", out.get("control_plane_location", "eastus2"))
    out["control_plane_location"] = location

    rgs = dict(out.get("resource_groups") or {})
    cp_rgs = {k: rgs[k] for k in engine.CONTROL_PLANE_ROLES if k in rgs}
    region_rgs = {k: rgs[k] for k in engine.REGION_ROLES if k in rgs}
    if cp_rgs:
        out["resource_groups"] = cp_rgs

    network = out.pop("network", None)
    fslogix = out.pop("fslogix", None)

    region_entry: dict = {}
    if region_rgs:
        region_entry["resource_groups"] = region_rgs
    if network is not None:
        region_entry["network"] = network
    region_entry["fslogix"] = fslogix

    out["regions"] = {location: region_entry}
    return out


def upgrade_config_tfvars(v1: dict, default_ws_key: str = "ws-avd") -> dict:
    """Upgrade a v1 02-nerdio-config tfvars dictionary to the v2 workspaces map structure."""
    if "workspaces" in v1 and "workspace" not in v1:
        return dict(v1)
    out = dict(v1)
    ws = out.pop("workspace", None)
    if isinstance(ws, dict):
        ws_key = ws.get("name") or default_ws_key
        out["workspaces"] = {ws_key: ws}
    out.pop("location", None)
    out.pop("hostpools_resource_group_name", None)
    out.pop("network", None)
    out.pop("fslogix_profile_share_unc", None)
    return out


def platform_moved_blocks(location: str) -> str:
    """Return Terraform `moved` blocks for 01-platform v1 -> v2 state migration."""
    return (
        "# Generated by ./nerdio migrate for v1 -> v2 state migration.\n"
        "# Safe to delete after running `terraform apply` on v2.\n\n"
        "moved {\n"
        '  from = module.foundation.azurerm_resource_group.this["network"]\n'
        f'  to   = module.spoke_foundation["{location}"].azurerm_resource_group.this["network"]\n'
        "}\n\n"
        "moved {\n"
        '  from = module.foundation.azurerm_resource_group.this["hostpools"]\n'
        f'  to   = module.spoke_foundation["{location}"].azurerm_resource_group.this["hostpools"]\n'
        "}\n\n"
        "moved {\n"
        '  from = module.foundation.azurerm_resource_group.this["storage"]\n'
        f'  to   = module.spoke_foundation["{location}"].azurerm_resource_group.this["storage"]\n'
        "}\n\n"
        "moved {\n"
        "  from = module.network\n"
        f'  to   = module.network["{location}"]\n'
        "}\n\n"
        "moved {\n"
        "  from = module.fslogix[0]\n"
        f'  to   = module.fslogix["{location}"]\n'
        "}\n"
    )


def config_moved_blocks(location: str, workspace_key: str) -> str:
    """Return Terraform `moved` blocks for 02-nerdio-config v1 -> v2 state migration."""
    return (
        "# Generated by ./nerdio migrate for v1 -> v2 state migration.\n"
        "# Safe to delete after running `terraform apply` on v2.\n\n"
        "moved {\n"
        "  from = module.nerdio_config.nme_linked_resource_group.hostpools\n"
        f'  to   = module.nerdio_config.nme_linked_resource_group.hostpools["{location}"]\n'
        "}\n\n"
        "moved {\n"
        "  from = module.nerdio_config.nme_linked_resource_group.network[0]\n"
        f'  to   = module.nerdio_config.nme_linked_resource_group.network["{location}"]\n'
        "}\n\n"
        "moved {\n"
        "  from = module.nerdio_config.nme_linked_network.session_hosts\n"
        f'  to   = module.nerdio_config.nme_linked_network.session_hosts["{location}"]\n'
        "}\n\n"
        "moved {\n"
        "  from = module.nerdio_config.nme_workspace.this\n"
        f'  to   = module.nerdio_config.nme_workspace.this["{workspace_key}"]\n'
        "}\n"
    )


def _write_private_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    old = os.umask(0o077)
    try:
        path.write_text(content, encoding="utf-8")
    finally:
        os.umask(old)


def migrate_environment(schema: dict, env: str) -> list[Path]:
    """Upgrade existing setup.auto.tfvars.json files and write migrations.auto.tf in both stages."""
    written: list[Path] = []
    answers = engine.load_answers()
    platform_dir = engine.stage_dir(schema, "platform", env)
    config_dir = engine.stage_dir(schema, "config", env)

    platform_tfvars_path = platform_dir / schema["output_file"]
    config_tfvars_path = config_dir / schema["output_file"]

    location = answers.get("location", "eastus2")
    prefix = answers.get("prefix", f"nme-{answers.get('environment', 'sandbox')}-{answers.get('_random4', 'ab12')}")
    workspace_key = f"ws-{prefix}"

    if platform_tfvars_path.exists():
        raw_plat = json.loads(platform_tfvars_path.read_text(encoding="utf-8"))
        location = raw_plat.get("location") or raw_plat.get("control_plane_location") or location
        upgraded_plat = upgrade_platform_tfvars(raw_plat)
        _write_private_text(platform_tfvars_path, json.dumps(upgraded_plat, indent=2) + "\n")
        written.append(platform_tfvars_path)

    if config_tfvars_path.exists():
        raw_cfg = json.loads(config_tfvars_path.read_text(encoding="utf-8"))
        if isinstance(raw_cfg.get("workspace"), dict) and raw_cfg["workspace"].get("name"):
            workspace_key = raw_cfg["workspace"]["name"]
        elif isinstance(raw_cfg.get("workspaces"), dict) and raw_cfg["workspaces"]:
            workspace_key = sorted(raw_cfg["workspaces"].keys())[0]
        upgraded_cfg = upgrade_config_tfvars(raw_cfg, default_ws_key=workspace_key)
        _write_private_text(config_tfvars_path, json.dumps(upgraded_cfg, indent=2) + "\n")
        written.append(config_tfvars_path)

    plat_mig = platform_dir / "migrations.auto.tf"
    _write_private_text(plat_mig, platform_moved_blocks(location))
    written.append(plat_mig)

    cfg_mig = config_dir / "migrations.auto.tf"
    _write_private_text(cfg_mig, config_moved_blocks(location, workspace_key))
    written.append(cfg_mig)

    return written
